def table_checks(machine: str) -> list[str]:
    rows = machine.split("_")
    assert len(rows) == len(STATES), (len(rows), len(STATES))
    out = []
    for state, row in zip(STATES, rows):
        assert len(row) == 6, row
        cells = []
        for sym, entry in ((0, row[:3]), (1, row[3:])):
            if entry == "---":
                rhs = "None"
            else:
                write, move, nxt = entry[0], entry[1], entry[2]
                assert write in "01" and move in "LR" and nxt in STATES, entry
                rhs = f"Some ({write}, TM.{move}, {nxt})"
            cells.append(f"Check (eq_refl : BB13_BakersDozen.tm ({state}, {sym}) = {rhs}).")
        out.append("  ".join(cells))
    return out


def probe_text() -> str:
    lines = [
        "(** Independent probe for the Baker's Dozen proofs (generated by gen_probe.py from the machine string; run after",
        "    compile_clean.sh, in this directory:  coqc -Q $BUSYCOQ BusyCoq -Q . BB8 probe.v).",
        "",
        "    Coq confirms here, by conversion, that (1) the compiled transition table of [BB13_BakersDozen.tm] is the machine",
        f"    {MACHINE}",
        "    entry by entry (the 26 lines below were generated from the machine string, not from the Coq file; the",
        "    undefined transition M1 '---' is None), and the start configuration is the blank tape in state A; (2) the",
        "    main theorems have the stated types; (3) they and the main rules use no axioms.  It also prints the",
        "    definitions the statements use.  The 13-state setup names a state L, so directions are written TM.L /",
        "    TM.R. *)",
        "",
        "From BB8 Require BB13_BakersDozen BB13_BakersDozen_bound.",
        "From BB8 Require Import Individual132.",
        "From Coq Require Import PeanoNat.",
        "Local Open Scope sym_scope.",
        "",
        "Print c0.",
        "Check (eq_refl : q0 = A).  Check (eq_refl : s0 = S0).",
        *table_checks(MACHINE),
        "",
        *(f"Print {name}." for name in PRINTED),
        "",
        *(f"Check {name}." for name in MAIN_THEOREMS),
        "",
        *(f"Print Assumptions {name}." for name in MAIN_THEOREMS),
        "",
        "(* the rules the run is built from *)",
        *(f"Print Assumptions {name}." for name in RULES),
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    out = Path(__file__).with_name("probe.v")
    out.write_text(probe_text(), encoding="utf-8", newline="\n")
    print(f"wrote {out} ({len(MAIN_THEOREMS)} main theorems, {len(RULES)} rules)")


if __name__ == "__main__":
    main()
